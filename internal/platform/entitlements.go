package platform

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"reflect"
)

// ReconcileEntitlement projects one paid subscription into its owned identity.
// A committed identity is desired state only: node delivery must establish a
// managed gate and quota before enabling it. No network runs in this transaction.
func (s *Store) ReconcileEntitlement(ctx context.Context) (bool, error) {
	ran := false
	e := s.transaction(ctx, func(tx *sql.Tx) error {
		now := s.now().Unix()
		sub, e := scanSubscription(tx.QueryRowContext(ctx, `SELECT `+subscriptionColumns+` FROM subscriptions WHERE entitlement_next_attempt<=? AND
   (identity_id IS NOT NULL OR EXISTS(SELECT 1 FROM paid_periods p WHERE p.subscription_id=subscriptions.id AND p.starts_at<=? AND p.ends_at>?))
   ORDER BY entitlement_next_attempt,id LIMIT 1`, now, now, now))
		if errors.Is(e, ErrNotFound) {
			return nil
		}
		if e != nil {
			return e
		}
		ran = true
		var customerEnabled bool
		if e = tx.QueryRowContext(ctx, "SELECT enabled FROM customers WHERE id=?", sub.CustomerID).Scan(&customerEnabled); e != nil {
			return e
		}
		var period *PaidPeriod
		if sub.Enabled && customerEnabled {
			p, e := paidPeriodTx(ctx, tx, sub.ID, now)
			if e != nil && !errors.Is(e, ErrNotFound) {
				return e
			}
			if e == nil {
				period = &p
			}
		}
		next := now + 30
		if period != nil {
			next = min(next, period.EndsAt)
		}
		var future *int64
		if e = tx.QueryRowContext(ctx, "SELECT MIN(starts_at) FROM paid_periods WHERE subscription_id=? AND starts_at>?", sub.ID, now).Scan(&future); e != nil {
			return e
		}
		if future != nil {
			next = min(next, *future)
		}
		if _, e = tx.ExecContext(ctx, "UPDATE subscriptions SET entitlement_next_attempt=? WHERE id=?", next, sub.ID); e != nil {
			return e
		}
		if sub.IdentityID == "" {
			if period == nil {
				return nil
			}
			var count int
			if e = tx.QueryRowContext(ctx, "SELECT count(*) FROM identities WHERE cluster_id=?", sub.ClusterID).Scan(&count); e != nil {
				return e
			}
			if count >= MaxIdentities {
				return auditTx(ctx, tx, now, "subscription.identity.capacity", sub.ID, 0)
			}
			if e = tx.QueryRowContext(ctx, "SELECT COUNT(*) FROM identities WHERE cluster_id=? AND username=?", sub.ClusterID, sub.ID).Scan(&count); e != nil {
				return e
			}
			if count != 0 {
				return auditTx(ctx, tx, now, "subscription.identity.name_conflict", sub.ID, 0)
			}
			id := newID("i_")
			secret := randomSecret()
			policy := period.Terms.NodePolicy
			raw, _ := json.Marshal(policy)
			// Subscription IDs are generated by this store and fit Telemt usernames.
			if !usernamePattern.MatchString(sub.ID) {
				return ErrSchema
			}
			_, e = tx.ExecContext(ctx, `INSERT INTO identities(id,cluster_id,username,secret_cipher,secret_hash,policy,revision,created_at,updated_at) VALUES(?,?,?,?,?,?,1,?,?)`, id, sub.ClusterID, sub.ID, s.encrypt(sub.ClusterID+":"+id, secret), secretHash(secret), string(raw), now, now)
			if e != nil {
				return e
			}
			if _, e = tx.ExecContext(ctx, "INSERT INTO identity_credentials(identity_id,secret_hash,revision) VALUES(?,?,1)", id, secretHash(secret)); e != nil {
				return e
			}
			if _, e = tx.ExecContext(ctx, "UPDATE subscriptions SET identity_id=?,updated_at=? WHERE id=? AND identity_id IS NULL", id, now, sub.ID); e != nil {
				return e
			}
			if _, e = tx.ExecContext(ctx, `INSERT INTO identity_jobs(identity_id,node_id,desired_revision,status,next_attempt,updated_at) SELECT ?,node_id,1,'pending',?,? FROM cluster_members WHERE cluster_id=? AND state='active'`, id, now, now, sub.ClusterID); e != nil {
				return e
			}
			return auditTx(ctx, tx, now, "subscription.identity.create", sub.ID, 1)
		}
		identity, e := scanIdentity(tx.QueryRowContext(ctx, "SELECT "+identityColumns+" FROM identities WHERE id=?", sub.IdentityID))
		if e != nil {
			return e
		}
		if identity.ClusterID != sub.ClusterID {
			return ErrSchema
		}
		if identity.Revoked {
			return nil
		} // A new payment cannot undo an explicit revocation.
		desired := identity.Policy
		desired.Enabled = false
		if period != nil {
			desired = period.Terms.NodePolicy
		}
		if reflect.DeepEqual(desired, identity.Policy) {
			return nil
		}
		raw, _ := json.Marshal(desired)
		if _, e = tx.ExecContext(ctx, "UPDATE identities SET policy=?,revision=revision+1,updated_at=? WHERE id=?", string(raw), now, identity.ID); e != nil {
			return e
		}
		if _, e = tx.ExecContext(ctx, "UPDATE identity_jobs SET desired_revision=?,status='pending',attempts=0,next_attempt=?,lease_until=0,lease_token='',last_code='',updated_at=? WHERE identity_id=?", identity.Revision+1, now, now, identity.ID); e != nil {
			return e
		}
		return auditTx(ctx, tx, now, "subscription.entitlement", sub.ID, identity.Revision+1)
	})
	return ran, e
}
func paidPeriodTx(ctx context.Context, tx *sql.Tx, subscriptionID string, now int64) (PaidPeriod, error) {
	var p PaidPeriod
	var raw string
	e := tx.QueryRowContext(ctx, `SELECT id,subscription_id,invoice_id,plan_id,plan_version,starts_at,ends_at,terms FROM paid_periods WHERE subscription_id=? AND starts_at<=? AND ends_at>? ORDER BY starts_at DESC LIMIT 1`, subscriptionID, now, now).Scan(&p.ID, &p.SubscriptionID, &p.InvoiceID, &p.PlanID, &p.PlanVersion, &p.StartsAt, &p.EndsAt, &raw)
	if errors.Is(e, sql.ErrNoRows) {
		return p, ErrNotFound
	}
	if e != nil {
		return p, e
	}
	p.Terms, e = decodeTerms(raw)
	if e != nil {
		return p, e
	}
	if _, e = cleanTerms(p.Terms, 0); e != nil {
		return p, ErrSchema
	}
	return p, nil
}
