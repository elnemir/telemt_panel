// Package ingress renders a bounded, typed HAProxy configuration. It never
// accepts caller-provided directives, certificate paths or shell arguments.
package ingress

import (
	"crypto/sha256"
	"errors"
	"fmt"
	"net/netip"
	"regexp"
	"sort"
	"strings"
)

var ErrInvalid = errors.New("invalid ingress configuration")
var domainLabel = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$`)

type Target struct {
	NodeID        string `json:"node_id"`
	NativeAddress string `json:"native_address"`
	WebAddress    string `json:"web_address"`
	Weight        int    `json:"weight"`
	Drain         bool   `json:"drain"`
}
type Config struct {
	Domain        string   `json:"domain"`
	NativePort    int      `json:"native_port"`
	WebPort       int      `json:"web_port"`
	NativeBalance string   `json:"native_balance"`
	Targets       []Target `json:"targets"`
}

func (c Config) Validate() error {
	if (c.WebPort != 0 || c.Domain != "") && !validDomain(c.Domain) {
		return ErrInvalid
	}
	if c.NativePort < 1 || c.NativePort > 65535 || (c.WebPort != 0 && c.WebPort != 443) || c.NativePort == c.WebPort {
		return ErrInvalid
	}
	switch c.NativeBalance {
	case "roundrobin", "leastconn", "source":
	default:
		return ErrInvalid
	}
	if len(c.Targets) < 1 || len(c.Targets) > 64 {
		return ErrInvalid
	}
	seen := map[string]bool{}
	for _, t := range c.Targets {
		if len(t.NodeID) == 0 || len(t.NodeID) > 128 || seen[t.NodeID] || t.Weight < 1 || t.Weight > 256 {
			return ErrInvalid
		}
		seen[t.NodeID] = true
		if !validAddress(t.NativeAddress) {
			return ErrInvalid
		}
		if (c.WebPort == 0 && t.WebAddress != "") ||
			(c.WebPort != 0 && (!validAddress(t.WebAddress) || t.NativeAddress == t.WebAddress)) {
			return ErrInvalid
		}
	}
	return nil
}

func validDomain(domain string) bool {
	if len(domain) > 253 || !strings.Contains(domain, ".") {
		return false
	}
	for _, label := range strings.Split(domain, ".") {
		if !domainLabel.MatchString(label) {
			return false
		}
	}
	_, err := netip.ParseAddr(domain)
	return err != nil
}

func validAddress(raw string) bool {
	addr, err := netip.ParseAddrPort(raw)
	return err == nil && addr.Port() != 0 && !addr.Addr().IsUnspecified() &&
		!addr.Addr().IsMulticast() && addr.Addr().Zone() == "" && addr.String() == raw
}

const initialHealthState = ".if version_atleast(3.2)\n    default-server init-state fully-down\n.endif\n"

func serverName(nodeID string) string {
	sum := sha256.Sum256([]byte(nodeID))
	return fmt.Sprintf("n%x", sum[:16])
}
func (c Config) Render() (string, error) {
	if e := c.Validate(); e != nil {
		return "", e
	}
	targets := append([]Target(nil), c.Targets...)
	sort.Slice(targets, func(i, j int) bool { return targets[i].NodeID < targets[j].NodeID })
	var out strings.Builder
	out.WriteString("# Generated by Telemt panel.\nglobal\n    maxconn 10000\n    noreuseport\n    spread-checks 10\n\ndefaults\n    no log\n    timeout connect 5s\n    timeout client 65s\n    timeout server 65s\n    timeout tunnel 1h\n    retries 0\n\n")
	fmt.Fprintf(&out, "frontend native\n    mode tcp\n    option clitcpka\n    timeout client-fin 30s\n    bind :%d\n    default_backend native_nodes\n\nbackend native_nodes\n    mode tcp\n    option srvtcpka\n    timeout server-fin 30s\n    balance %s\n", c.NativePort, c.NativeBalance)
	if c.NativeBalance == "source" {
		out.WriteString("    hash-type consistent\n")
	}
	out.WriteString(initialHealthState)
	for _, t := range targets {
		weight := t.Weight
		if t.Drain {
			weight = 0
		}
		fmt.Fprintf(&out, "    server %s %s weight %d check inter 2s fall 2 rise 2 send-proxy-v2\n", serverName(t.NodeID), t.NativeAddress, weight)
	}
	if c.WebPort == 0 {
		return out.String(), nil
	}
	fmt.Fprintf(&out, "\nfrontend web\n    mode http\n    timeout http-request 10s\n    bind :%d ssl crt /etc/telemt-ingress/tls.pem alpn h2,http/1.1\n    acl allowed_host hdr(host) -i %s %s:%d\n    http-request deny deny_status 421 unless allowed_host\n    http-request set-header Host %s\n    http-request del-header Forwarded\n    http-request del-header X-Forwarded-For\n    http-request set-header X-Forwarded-For %%[src]\n    http-request set-header X-Forwarded-Proto https\n    default_backend web_nodes\n\nbackend web_nodes\n    mode http\n    balance source\n    hash-type consistent\n    option http-keep-alive\n    cookie TELEMT_INGRESS insert indirect nocache httponly secure attr SameSite=Lax\n", c.WebPort, c.Domain, c.Domain, c.WebPort, c.Domain)
	out.WriteString(initialHealthState)
	for _, t := range targets {
		weight := t.Weight
		if t.Drain {
			weight = 0
		}
		name := serverName(t.NodeID)
		fmt.Fprintf(&out, "    server %s %s weight %d cookie %s check inter 2s fall 2 rise 2\n", name, t.WebAddress, weight, name)
	}
	return out.String(), nil
}
