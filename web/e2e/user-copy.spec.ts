import {expect,test} from "./fixtures";
import {execFileSync,spawn,type ChildProcess} from "node:child_process";
import {mkdtemp,rm} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import {killAndWait} from "./stack";

let scratch="",mock:ChildProcess|undefined;
const url="http://127.0.0.1:48195";
const headers={"Sec-Fetch-Site":"same-origin"};
test.beforeAll(async()=>{
 scratch=await mkdtemp("/private/tmp/telemt-copy-e2e-");
 execFileSync("go",["build","-o",scratch+"/mock","./cmd/telemt-mock"],{cwd:fileURLToPath(new URL("../../",import.meta.url))});
 mock=spawn(scratch+"/mock",["-listen","127.0.0.1:48195","-scenario","full"],{stdio:"ignore"});
 await expect.poll(async()=>{try{return(await fetch(url+"/v1/health")).ok;}catch{return false;}}).toBe(true);
});
test.afterAll(async()=>{if(mock)await killAndWait(mock);if(scratch)await rm(scratch,{recursive:true,force:true});});
test("copy preview, target verification, conflict and retained command",async({page,login},info)=>{
 test.skip(process.env["CONTROL_PLANE_ONLY"]==="1","uses configured default source");
 test.setTimeout(90000);
 await login();
 const username="copied-"+info.project.name;
 expect((await page.request.post("/api/users",{headers,data:{username,secret:"0123456789abcdef0123456789abcdef",max_tcp_conns:9}})).status()).toBe(201);
 const created=await page.request.post("/api/nodes",{headers,data:{name:"Copy target",api_url:url,enabled:true}});
 expect(created.status()).toBe(201);const node=await created.json();
 await page.goto(`/people/${username}?tab=access`);
 await page.getByRole("button",{name:"Копировать на ноды",exact:true}).click();
 const sheet=page.getByRole("dialog",{name:"Копировать на ноды",exact:true});
 await sheet.getByLabel("Copy target",{exact:true}).check();
 await sheet.getByRole("button",{name:"Предварительный просмотр",exact:true}).click();
 await expect(sheet.getByText("Будет создан",{exact:true})).toBeVisible();
 expect((await page.request.get(`/api/nodes/${node.id}/manage/users/${username}`)).status()).toBe(404);
 await sheet.getByRole("button",{name:"Выполнить копирование",exact:true}).click();
 await expect(sheet.getByText("Сохранено и проверено",{exact:true})).toBeVisible();
 const target=await(await page.request.get(`/api/nodes/${node.id}/manage/users/${username}`)).json();
 expect(target.max_tcp_conns).toBe(9);
 expect(target.links.classic[0]).toContain("secret=0123456789abcdef0123456789abcdef");
 await page.screenshot({path:info.outputPath("copy-result.png"),fullPage:true});
 await page.reload();
 await page.getByRole("button",{name:"Копировать на ноды",exact:true}).click();
 await expect(sheet.getByText("Сохранено и проверено",{exact:true})).toBeVisible();
 await sheet.getByRole("button",{name:"Новый просмотр",exact:true}).click();
 await sheet.getByLabel("Copy target",{exact:true}).check();
 await sheet.getByRole("button",{name:"Предварительный просмотр",exact:true}).click();
 await expect(sheet.getByText("Пропущено",{exact:true})).toBeVisible();
 await expect(sheet.getByRole("button",{name:"Выполнить копирование",exact:true})).toBeDisabled();
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
 expect((await page.request.delete("/api/users/"+username,{headers})).status()).toBe(204);
 expect((await page.request.delete(`/api/nodes/${node.id}/manage/users/${username}`,{headers})).status()).toBe(204);
 expect((await page.request.delete("/api/nodes/"+node.id,{headers:{...headers,"If-Match":String(node.revision)}})).status()).toBe(204);
});
