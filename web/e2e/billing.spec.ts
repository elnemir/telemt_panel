import {expect,test} from "./fixtures";
const headers={"Sec-Fetch-Site":"same-origin"};
test("versioned tariffs and immutable payment connections",async({page,login},info)=>{
 test.skip(process.env["TELEMT_PLATFORM_E2E"]!=="1","requires durable platform");
 await login();
 const suffix=info.project.name;
 const response=await page.request.post("/api/clusters",{headers,data:{name:"Billing "+suffix}});
 expect(response.status()).toBe(201);const cluster=await response.json();
 await page.goto("/billing");
 await page.getByRole("button",{name:"Создать тариф",exact:true}).click();
 let sheet=page.getByRole("dialog",{name:"Создать тариф",exact:true});
 await sheet.getByLabel("Название",{exact:true}).fill("Tariff "+suffix);
 await sheet.getByLabel("Кластер",{exact:true}).selectOption(cluster.id);
 await sheet.getByLabel("Доступен для новых покупок",{exact:true}).check();
 await sheet.getByLabel("Цена в минимальных единицах валюты",{exact:true}).fill("9900");
 await sheet.getByLabel("Длительность периода, секунд",{exact:true}).fill("86400");
 await sheet.getByLabel("Квота периода, байт",{exact:true}).fill("9007199254740993");
 await sheet.getByLabel("Допустимое превышение, байт",{exact:true}).fill("1048576");
 await sheet.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(sheet).not.toBeVisible();
 let card=page.getByRole("listitem").filter({has:page.getByRole("heading",{name:"Tariff "+suffix,exact:true})});
 await expect(card.getByText("99.00 RUB",{exact:true})).toBeVisible();
 let plans=await(await page.request.get("/api/billing/plans?cluster_id="+cluster.id)).json();
 expect(plans[0].terms.quota_bytes).toBe("9007199254740993");
 const plan=plans[0];
 await card.getByRole("button",{name:"Новая версия тарифа",exact:true}).click();
 sheet=page.getByRole("dialog",{name:"Новая версия тарифа",exact:true});
 await expect(sheet.getByLabel("Кластер",{exact:true})).toBeDisabled();
 await sheet.getByLabel("Цена в минимальных единицах валюты",{exact:true}).fill("19900");
 await sheet.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(sheet).not.toBeVisible();
 await expect(card.getByText("199.00 RUB",{exact:true})).toBeVisible();
 plans=await(await page.request.get("/api/billing/plans?cluster_id="+cluster.id)).json();expect(plans[0].version).toBe(2);
 // Form revision belongs to its original snapshot, even if another admin writes.
 await card.getByRole("button",{name:"Новая версия тарифа",exact:true}).click();
 sheet=page.getByRole("dialog",{name:"Новая версия тарифа",exact:true});
 expect((await page.request.put("/api/billing/plans/"+plan.id,{headers:{...headers,"If-Match":"2"},data:{name:"Tariff "+suffix,enabled:true,terms:plans[0].terms}})).status()).toBe(204);
 await sheet.getByLabel("Цена в минимальных единицах валюты",{exact:true}).fill("29900");
 await sheet.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(sheet.getByRole("alert")).toBeVisible();
 page.on("dialog",d=>void d.accept());await sheet.getByRole("button",{name:"Отмена",exact:true}).click();await expect(sheet).not.toBeVisible();
 await page.getByRole("button",{name:"Добавить подключение",exact:true}).click();
 sheet=page.getByRole("dialog",{name:"Добавить подключение",exact:true});
 await sheet.getByLabel("Название",{exact:true}).fill("Merchant "+suffix);
 await sheet.getByLabel("Идентификатор магазина",{exact:true}).fill("merchant-test");
 await sheet.getByLabel("Переменная пароля №1",{exact:true}).fill("TELEMT_PAYMENT_E2E_P1");
 await sheet.getByLabel("Переменная пароля №2",{exact:true}).fill("TELEMT_PAYMENT_E2E_P2");
 await sheet.getByLabel("Передавать номенклатуру чека Robokassa",{exact:true}).check();
 await sheet.getByLabel("Наименование услуги в чеке",{exact:true}).fill("Proxy service");
 await sheet.getByLabel("Налог",{exact:true}).selectOption("none");
 await sheet.getByLabel("Способ расчёта",{exact:true}).selectOption("full_payment");
 await sheet.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(sheet).not.toBeVisible();
 card=page.getByRole("listitem").filter({has:page.getByRole("heading",{name:"Merchant "+suffix,exact:true})});
 await card.getByRole("button",{name:"Изменить",exact:true}).click();
 sheet=page.getByRole("dialog",{name:"Настройки подключения",exact:true});
 await expect(sheet.getByLabel("Провайдер",{exact:true})).toBeDisabled();
 await expect(sheet.getByLabel("Переменная пароля №1",{exact:true})).toHaveValue("TELEMT_PAYMENT_E2E_P1");
 await expect(sheet.getByLabel("Переменная пароля №1",{exact:true})).toBeDisabled();
 await expect(sheet.getByLabel("URL уведомлений (POST)",{exact:true})).toHaveValue(/\/api\/payments\/merchant_[a-f0-9]+\/notify$/);
 await sheet.getByLabel("Название",{exact:true}).fill("Renamed "+suffix);
 await sheet.getByRole("button",{name:"Сохранить",exact:true}).click();await expect(sheet).not.toBeVisible();
 await expect(page.getByRole("heading",{name:"Renamed "+suffix,exact:true})).toBeVisible();
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
 await page.getByRole("heading",{name:"Биллинг",exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:info.outputPath("billing.png"),fullPage:true});
});
